import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg', '.avif']);

const isImageFile = (filename) => IMAGE_EXTENSIONS.has(path.extname(filename).toLowerCase());

const scanDir = (dirPath) => {
  try {
    if (!fs.existsSync(dirPath)) return [];
    return fs.readdirSync(dirPath).filter(isImageFile);
  } catch {
    return [];
  }
};

const findFileByBaseName = (dirPath, baseName, publicRoot) => {
  const files = scanDir(dirPath);
  const match = files.find((file) => path.parse(file).name.toLowerCase() === baseName.toLowerCase());

  if (!match) return null;

  const rel = path.relative(publicRoot, path.join(dirPath, match));
  return `/${rel.replace(/\\/g, '/')}`;
};

const generateManifest = (publicRoot) => {
  const imagesRoot = path.join(publicRoot, 'images');
  const profileDir = path.join(imagesRoot, 'profile');
  const coversDir = path.join(imagesRoot, 'covers');
  const detailsDir = path.join(imagesRoot, 'details');

  const avatar = findFileByBaseName(profileDir, 'avatar', publicRoot);
  const avatarDark = findFileByBaseName(profileDir, 'avatar-dark', publicRoot);

  const covers = {};
  const coverBaseNames = new Set();

  for (const file of scanDir(coversDir)) {
    const name = path.parse(file).name.toLowerCase();
    coverBaseNames.add(name.replace(/-dark$/, ''));
  }

  for (const projectId of coverBaseNames) {
    const light = findFileByBaseName(coversDir, projectId, publicRoot);
    const dark = findFileByBaseName(coversDir, `${projectId}-dark`, publicRoot);

    if (light) {
      covers[projectId] = { light, dark };
    }
  }

  const details = {};

  try {
    if (fs.existsSync(detailsDir)) {
      const projectDirs = fs
        .readdirSync(detailsDir, { withFileTypes: true })
        .filter((entry) => entry.isDirectory());

      for (const dir of projectDirs) {
        const projectDir = path.join(detailsDir, dir.name);
        details[dir.name] = scanDir(projectDir)
          .sort((a, b) => {
            const numA = Number.parseInt(path.parse(a).name, 10);
            const numB = Number.parseInt(path.parse(b).name, 10);

            if (!Number.isNaN(numA) && !Number.isNaN(numB)) return numA - numB;
            return a.localeCompare(b);
          })
          .map((file) => {
            const rel = path.relative(publicRoot, path.join(projectDir, file));
            return `/${rel.replace(/\\/g, '/')}`;
          });
      }
    }
  } catch {
    // Missing or temporarily incomplete detail folders should not block manifest generation.
  }

  return { profile: { avatar, avatarDark }, covers, details };
};

const writeManifestFile = (projectRoot, manifest) => {
  const outputPath = path.join(projectRoot, 'data', 'imageManifest.ts');
  const content = `/**
 * This file is generated by scripts/sync-image-manifest.mjs.
 * Do not edit it by hand.
 */

export const imageManifest = ${JSON.stringify(manifest, null, 2)} as const;

export type ProjectImageId = keyof typeof imageManifest.covers;
`;

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  const previous = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;

  if (previous !== content) {
    fs.writeFileSync(outputPath, content, 'utf8');
    return { changed: true, outputPath };
  }

  return { changed: false, outputPath };
};

try {
  const projectRoot = process.cwd();
  const manifest = generateManifest(path.join(projectRoot, 'public'));
  const result = writeManifestFile(projectRoot, manifest);

  console.log(`[images] Manifest ${result.changed ? 'updated' : 'checked'} at ${result.outputPath}.`);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
